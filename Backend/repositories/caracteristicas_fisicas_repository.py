from typing import Any, Protocol


class ContenidoCaracteristicasRepository(Protocol):
    def get_configuracion(self, seudonimo: str) -> dict[str, Any]: ...

    def get_texto(self, clave: str) -> str: ...

    def get_campos(self) -> list[dict[str, Any]]: ...

    def get_opciones(self, campo_clave: str) -> list[str]: ...


class CaracteristicasFisicasRepository(Protocol):
    def obtener(self, usuario_id: str) -> dict[str, Any] | None: ...

    def guardar(self, usuario_id: str, valores: dict[str, Any]) -> None: ...
